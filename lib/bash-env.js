/**
 * BASH_ENV helpers for the subprocess spawn bridge.
 *
 * A bash process can only read one BASH_ENV file. When another plugin writes
 * BASH_ENV after this one, the shim would stop running. The bridge therefore
 * injects the shim into the spawn spec and chains every earlier BASH_ENV file
 * through a generated chain file, so no plugin loses its shim.
 */

import { createHash } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const CHAIN_CACHE = new Set();

/**
 * @param {string} value
 * @returns {string} a single-quoted bash word
 */
export function quote(value) {
	return "'" + String(value).replace(/'/g, "'\\''") + "'";
}

/**
 * @param {string} value
 * @returns {string} path normalized for comparison
 */
export function normalizePath(value) {
	let text = String(value).replace(/\\/g, '/');
	if (process.platform === 'win32') {
		text = text.replace(/^\/\/\?\//, '').replace(/^\/\?\//, '');
		const drive = /^\/([A-Za-z])\/(.*)$/.exec(text);
		if (drive) text = drive[1] + ':/' + drive[2];
		text = text.toLowerCase();
	}
	return text;
}

/**
 * Pick the earlier BASH_ENV this plugin should chain. The current value wins,
 * except when it is this plugin's own shim (a reload) or when a previous
 * PS51_PREV_BASH_ENV points at one. Returning undefined means the caller should
 * remove the variable instead of creating a self-reference.
 *
 * @param {unknown} currentBashEnv
 * @param {unknown} previousChain
 * @param {string} shimPath
 * @returns {string | undefined}
 */
export function choosePreviousBashEnv(currentBashEnv, previousChain, shimPath) {
	const current = typeof currentBashEnv === 'string' ? currentBashEnv : '';
	const previous = typeof previousChain === 'string' ? previousChain : '';
	if (current !== '' && !samePath(current, shimPath)) return current;
	if (previous !== '' && !samePath(previous, shimPath)) return previous;
	return undefined;
}

/**
 * @param {string} left
 * @param {string} right
 * @returns {boolean}
 */
export function samePath(left, right) {
	return normalizePath(left) === normalizePath(right);
}

/**
 * @param {unknown} value
 * @returns {value is string}
 */
function isNonEmptyString(value) {
	return typeof value === 'string' && value !== '';
}

/**
 * @param {Record<string, unknown>} env
 * @param {string} name
 * @returns {string | undefined}
 */
export function findEnvKey(env, name) {
	const target = name.toLowerCase();
	for (const key of Object.keys(env)) {
		if (key.toLowerCase() === target) return key;
	}
	return undefined;
}

/**
 * @param {Record<string, unknown>} env
 * @param {string} name
 * @returns {unknown}
 */
export function getEnv(env, name) {
	const key = findEnvKey(env, name);
	return key === undefined ? undefined : env[key];
}

/**
 * Set one environment entry without leaving a second spelling behind. Windows
 * environment names are case-insensitive, so "BASH_ENV" and "bash_env" would
 * otherwise both reach the child and the winner would be undefined.
 *
 * @param {Record<string, unknown>} env
 * @param {string} name
 * @param {string} value
 */
export function setEnv(env, name, value) {
	const target = name.toLowerCase();
	const key = findEnvKey(env, name);
	for (const other of Object.keys(env)) {
		if (other !== key && other.toLowerCase() === target) delete env[other];
	}
	env[key === undefined ? name : key] = value;
}

/**
 * @param {Record<string, unknown>} env
 * @param {string} name
 */
export function deleteEnv(env, name) {
	const target = name.toLowerCase();
	for (const key of Object.keys(env)) {
		if (key.toLowerCase() === target) delete env[key];
	}
}

/**
 * @param {unknown} argv
 * @returns {boolean} true for a bash -c style invocation
 */
export function isBashCommand(argv) {
	if (!Array.isArray(argv) || argv.length < 2) return false;
	const file = typeof argv[0] === 'string' ? argv[0] : '';
	if (!/(^|[\\/])(bash|niubash)(\.exe)?$/iu.test(file)) return false;
	return argv.slice(1).some((arg) => typeof arg === 'string' && /^-[a-z]*c[a-z]*$/iu.test(arg));
}

/**
 * Build a chain file that sources every earlier BASH_ENV in order. Each source
 * is guarded, so a removed plugin cannot make the last command fail.
 *
 * @param {string[]} paths
 * @returns {string}
 */
export function buildChainSource(paths) {
	const lines = ['# generated by dsh-ps51-guard: earlier BASH_ENV files'];
	for (const path of paths) {
		const word = quote(path);
		lines.push('if [ -r ' + word + ' ]; then . ' + word + '; fi');
	}
	return lines.join('\n') + '\n';
}

/**
 * Return a source path for the given earlier shims. One path needs no file;
 * two or more are cached by their normalized list so a busy spawn path does not
 * rewrite the same chain on every command.
 *
 * @param {string} runtime
 * @param {string[]} paths
 * @returns {string | null}
 */
export function chainFile(runtime, paths) {
	const unique = [];
	const seen = new Set();
	for (const path of paths) {
		if (!isNonEmptyString(path)) continue;
		const key = normalizePath(path);
		if (seen.has(key)) continue;
		seen.add(key);
		unique.push(path);
	}
	if (unique.length === 0) return null;
	if (unique.length === 1) return unique[0];
	const hash = createHash('sha1').update(unique.join('\u0000')).digest('hex').slice(0, 16);
	const file = join(runtime, 'bash-env-chain-' + hash + '.sh');
	if (!CHAIN_CACHE.has(file) || !existsSync(file)) {
		writeFileSync(file, buildChainSource(unique), 'utf8');
		CHAIN_CACHE.add(file);
	}
	return file;
}

/**
 * Inject this plugin's shim into a subprocess spawn spec.
 *
 * The call is deliberately conservative:
 * - only bash -c specs, or specs that already carry a non-empty BASH_ENV;
 * - an explicit empty BASH_ENV and PS51_GUARD=0 are respected;
 * - the input spec and env are never mutated;
 * - earlier shims become the generated chain file, so no plugin loses its
 *   BASH_ENV when this bridge wins the spawn.
 *
 * @param {unknown} spec
 * @param {{shimPath: string, runtime: string, ambientBashEnv?: string, ambientPrevBashEnv?: string, baseEnv?: Record<string, string | undefined>, warn?: (message: string) => void}} options
 * @returns {unknown}
 */
export function withGuardEnv(spec, options) {
	if (spec === null || typeof spec !== 'object' || Array.isArray(spec)) return spec;
	if (typeof options?.shimPath !== 'string' || options.shimPath === '') return spec;
	const bash = isBashCommand(/** @type {{argv?: unknown}} */ (spec).argv);
	let env = /** @type {Record<string, unknown>} */ (spec).env;
	if (env === undefined) {
		// An omitted env inherits process.env at spawn time. Copy it here so the
		// shim rides along even if another plugin rewrote process.env first.
		if (!bash || !options.baseEnv) return spec;
		env = { ...options.baseEnv };
	} else if (env === null || typeof env !== 'object' || Array.isArray(env)) return spec;
	if (getEnv(env, 'PS51_GUARD') === '0' || getEnv(env, 'PS51_GUARD') === 0) return spec;

	const current = getEnv(env, 'BASH_ENV');
	if (typeof current === 'string' && current === '') return spec;
	const hasCurrent = isNonEmptyString(current);
	if (!bash && !hasCurrent) return spec;
	const currentIsShim = hasCurrent && samePath(current, options.shimPath);

	const nextEnv = { ...env };
	const sources = [];
	const existingPrev = getEnv(nextEnv, 'PS51_PREV_BASH_ENV');
	if (isNonEmptyString(existingPrev) && !samePath(existingPrev, options.shimPath)) sources.push(existingPrev);
	if (hasCurrent && !samePath(current, options.shimPath)) sources.push(current);
	if (isNonEmptyString(options.ambientBashEnv) && !samePath(options.ambientBashEnv, options.shimPath)) {
		sources.push(options.ambientBashEnv);
	}
	if (isNonEmptyString(options.ambientPrevBashEnv) && !samePath(options.ambientPrevBashEnv, options.shimPath)) {
		sources.push(options.ambientPrevBashEnv);
	}
	if (currentIsShim && sources.length === 0) {
		const previousNow = getEnv(env, 'PS51_PREV_BASH_ENV');
		if (!isNonEmptyString(previousNow)) return spec;
		if (samePath(previousNow, options.shimPath)) {
			const cleaned = { ...env };
			deleteEnv(cleaned, 'PS51_PREV_BASH_ENV');
			return { .../** @type {Record<string, unknown>} */ (spec), env: cleaned };
		}
	}

	let previous = null;
	try {
		previous = chainFile(options.runtime || dirname(options.shimPath), sources);
	} catch (error) {
		options.warn?.('could not build the BASH_ENV chain (' + error.message + '); keeping one earlier shim');
		previous = sources.find((path) => !samePath(path, options.shimPath)) ?? null;
	}
	if (previous) setEnv(nextEnv, 'PS51_PREV_BASH_ENV', previous);
	else {
		const previousValue = getEnv(nextEnv, 'PS51_PREV_BASH_ENV');
		if (!isNonEmptyString(previousValue) || samePath(previousValue, options.shimPath)) {
			deleteEnv(nextEnv, 'PS51_PREV_BASH_ENV');
		}
	}
	setEnv(nextEnv, 'BASH_ENV', options.shimPath);
	return { .../** @type {Record<string, unknown>} */ (spec), env: nextEnv };
}
